create table if not exists public.quiz_leaderboard (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 24),
  quiz text not null check (quiz in ('psas','bab2')),
  score integer not null check (score between 0 and 100),
  correct integer not null,
  total integer not null,
  created_at timestamptz not null default now()
);
alter table public.quiz_leaderboard enable row level security;
create policy "Leaderboard can be read by everyone" on public.quiz_leaderboard for select using (true);
create policy "Anyone can submit a score" on public.quiz_leaderboard for insert with check (true);
